async (page) => {
  const browser = page.context().browser();
  const context = await browser.newContext({viewport: {width: 1280, height: 900}, acceptDownloads: true});
  const test = await context.newPage();
  const records = [];
  const errors = [];
  const requests = [];
  test.on('pageerror', error => errors.push(error.message));
  test.on('requestfailed', request => requests.push({url: request.url(), error: request.failure()}));
  const base = new URL('index.html?qa=browser-check', page.url()).href;
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const record = (name, detail = {}) => records.push({name, status: 'PASS', ...detail});
  const click = name => test.getByRole('button', {name, exact: true}).click();
  const snapshot = () => test.evaluate(() => FerryUI.snapshot());
  const importState = async fixture => {
    await click('Guide & saves');
    await click('Show save import');
    await test.locator('#save-input').fill(JSON.stringify(fixture));
    await click('Validate and import');
    if (await test.locator('#accept-replacement').isVisible()) await click('Confirm replacement');
  };
  try {
    await test.goto(base);
    await test.evaluate(() => localStorage.setItem('ferryman-v05-night', 'isolated-old-save-sentinel'));
    await click('New run in slot 1');
    await click('Board Child');
    await click('Depart with selected souls');
    assert((await test.locator('#error').innerText()).includes('Facilitator input'), 'Missing route feedback absent');
    assert((await snapshot()).round === '0', 'Missing routes advanced time');
    record('Missing facilitator data pauses departure without advancing');
    await click('Facilitator routes');
    await test.locator('#route-input').fill('[["DEST-HAVEN","UNKNOWN"]]');
    await click('Append offers');
    assert((await test.locator('.dialog-error').innerText()).includes('six destination'), 'Invalid IDs accepted');
    await test.locator('#route-input').fill(JSON.stringify([['DEST-HAVEN','DEST-STYX'],['DEST-ASPHODEL','DEST-ELYSIUM'],['DEST-TARTARUS','DEST-ACHERON']]));
    await click('Append offers');
    await click('Depart with selected souls');
    assert(!(await test.locator('.reveals').innerText()).includes('Elysium'), 'Hidden offer exposed');
    record('Route input validation and future concealment');
    await click('Continue without a memory');
    const routeView = await snapshot();
    await test.reload();
    assert((await snapshot()).uiStep === 'route', 'Route step not restored');
    await click('Review Haven');
    const reviewState = await snapshot();
    await test.reload();
    assert(JSON.stringify(await snapshot()) === JSON.stringify(reviewState), 'Review reload differs');
    await click('Back');
    assert((await snapshot()).round === routeView.round, 'Back advances round');
    await click('Review Haven');
    await click('Confirm action');
    await test.locator('.route-ledger summary').click();
    assert((await test.locator('.route-ledger').innerText()).includes('Haven / River Styx'), 'Consumed offer disappeared');
    await test.reload();
    await test.locator('.route-ledger summary').click();
    assert((await test.locator('.route-ledger').innerText()).includes('Chosen: Haven'), 'Consumed offer missing after reload');
    record('Revealed current-cycle offer history survives progress and reload');
    await test.getByLabel('Deliver Child', {exact: true}).check();
    await click('Resolve selected deliveries');
    assert((await snapshot()).quest === 'child-delivered', 'Child quest not recorded');
    await click('Continue without a memory');
    await click('Review return');
    await click('Confirm action');
    assert((await snapshot()).cycle === '2', 'Return did not begin cycle 2');
    assert((await snapshot()).routes.offers.length === 0, 'Cycle queue not reset');
    record('Guided delivery, return, preview, Back and exact reload');
    await click('Guide & saves');
    await click('Stop and save session');
    assert((await test.locator('h1').innerText()).includes('Stopped'), 'Voluntary stop not displayed');
    await test.reload();
    assert((await snapshot()).paused, 'Stop not saved');
    await click('Resume this session');
    record('Voluntary stop and resume without victory');
    const downloadPromise = test.waitForEvent('download');
    await click('Guide & saves');
    await click('Export save');
    const download = await downloadPromise;
    const stream = await download.createReadStream();
    const chunks = [];
    for await (const chunk of stream) chunks.push(chunk);
    const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'));
    assert(JSON.stringify(exported) === JSON.stringify(await snapshot()), 'Export bytes differ');
    await click('Close');
    await importState(exported);
    assert(JSON.stringify(exported) === JSON.stringify(await snapshot()), 'Import differs');
    record('Real save download bytes and UI import roundtrip');
    await click('Guide & saves');
    await click('Show save import');
    await test.locator('#save-input').fill('{"version":"0.5"}');
    await click('Validate and import');
    assert((await test.locator('.dialog-error').innerText()).includes('not a v0.6'), 'Old save accepted');
    await click('Close');
    assert(await test.evaluate(() => localStorage.getItem('ferryman-v05-night')) === 'isolated-old-save-sentinel', 'Old save modified');
    record('Older save namespace preserved; invalid import keeps active run');
    const makeFixture = options => test.evaluate(options => {
      let state = Ferry.create(55);
      const ids = options.passengers || ['SOUL-MERCHANT'];
      for (const id of ids) state = Ferry.transition(state, {type:'BOARD', id});
      state = Ferry.transition(state, {type:'APPEND_ROUTES', offers: options.offers || [['DEST-STYX','DEST-HAVEN']]});
      state = Ferry.transition(state, {type:'DEPART'});
      for (const memory of options.memories || []) {
        state.hand.push({id:'MEMORY-' + state.nextMemory, type:memory[0], source:memory[1]});
        state.nextMemory = (BigInt(state.nextMemory) + 1n).toString();
      }
      if (options.quest) state.quest = options.quest;
      if (options.light) state.light = options.light;
      Ferry.validate(state);
      return state;
    }, options);
    const overflow = await makeFixture({memories: [['MEM-FORESIGHT','SOUL-MERCHANT'],['MEM-FORESIGHT','SOUL-MERCHANT'],['MEM-LIGHT','SOUL-MOTHER']]});
    await importState(overflow);
    await click('Continue without a memory');
    await click('Review River Styx');
    await click('Confirm action');
    await test.getByLabel('Deliver Merchant', {exact:true}).check();
    await click('Resolve selected deliveries');
    assert((await snapshot()).hand.length === 4, 'Overflow not retained');
    await test.reload();
    assert((await snapshot()).phase === 'trim', 'Overflow phase lost');
    await click('Discard Light');
    assert((await snapshot()).hand.filter(memory=>memory.type==='MEM-FORESIGHT').length === 3, 'Repeated copies collapsed');
    record('Fresh repeated memory, overflow choice and overflow reload');
    const foresight = await makeFixture({memories:[['MEM-FORESIGHT','SOUL-MERCHANT']]});
    await importState(foresight);
    await click('Choose Foresight');
    assert((await test.locator('#error').innerText()).includes('Facilitator'), 'Missing Foresight data not explained');
    assert((await snapshot()).hand.length === 1, 'Unavailable Foresight spent');
    await click('Facilitator routes');
    await test.locator('#route-input').fill(JSON.stringify([['DEST-ACHERON','DEST-ASPHODEL'],['DEST-ELYSIUM','DEST-HAVEN'],['DEST-TARTARUS','DEST-STYX']]));
    await click('Append offers');
    await click('Choose Foresight');
    await click('Confirm action');
    const reveals = await test.locator('.reveals').innerText();
    assert(reveals.includes('Elysium') && !reveals.includes('Tartarus'), 'Foresight visibility wrong');
    const foresightSave = await snapshot();
    await test.reload();
    assert(JSON.stringify(foresightSave) === JSON.stringify(await snapshot()), 'Foresight save differs');
    record('Foresight exactly three offers, missing-data transaction, reload concealment');
    const passage = await makeFixture({passengers:['SOUL-MOTHER'], memories:[['MEM-PASSAGE','QUEST-FAMILY']], quest:'completed'});
    await importState(passage);
    await click('Choose Passage');
    await click('Review memory');
    await click('Confirm action');
    assert((await snapshot()).round === '0' && (await snapshot()).window.used && !(await snapshot()).boat.length, 'Passage empty return wrong');
    assert(await test.getByText('The memory allowance is already used for this return.').isVisible(), 'Return lock not explained');
    record('Passage targeting and empty-return memory lock');
    const fatal = await makeFixture({light:1});
    await importState(fatal);
    await click('Continue without a memory');
    await click('Review River Styx');
    assert(await test.getByText('This will extinguish the lantern before any delivery or reward.').isVisible(), 'Lethal confirmation absent');
    await click('Confirm action');
    assert((await snapshot()).phase === 'ended' && (await snapshot()).deliveries === '0', 'Fatal crossing delivered');
    record('Lethal confirmation and immediate loss before delivery');
    await click('New run');
    await click('Cancel');
    assert((await snapshot()).phase === 'ended', 'Cancel replaced run');
    await click('New run');
    await click('Confirm replacement');
    assert((await snapshot()).phase === 'boarding', 'Confirmed new run failed');
    record('Destructive New Run confirmation and cancel');
    await test.setViewportSize({width:390,height:844});
    assert(await test.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow layout overflows');
    await test.screenshot({path:'outputs/The_Ferryman_v0.6/verification/browser-narrow.png',fullPage:true});
    await click('Guide & saves');
    assert(await test.getByRole('heading',{name:'Guide & saves',exact:true}).isVisible(), 'Help absent');
    assert(await test.evaluate(() => document.querySelector('dialog').getBoundingClientRect().width <= innerWidth), 'Help overflows');
    await click('Close');
    await test.setViewportSize({width:1280,height:900});
    await test.screenshot({path:'outputs/The_Ferryman_v0.6/verification/browser-desktop.png',fullPage:true});
    assert(await test.evaluate(() => [...document.images].every(image => image.complete && image.naturalWidth > 0)), 'Visible images broken');
    record('Desktop and 390px narrow layout, help, image loading', {screenshots:['browser-desktop.png','browser-narrow.png']});
    const decodedAssets = await test.evaluate(async () => {
      const paths = [...new Set(Object.values(FerryArt))];
      return await Promise.all(paths.map(async path => {
        const image = new Image();
        image.src = path;
        await image.decode();
        return {path, width:image.naturalWidth, height:image.naturalHeight};
      }));
    });
    assert(decodedAssets.length === 23 && decodedAssets.every(asset => asset.width > 0 && asset.height > 0), 'Incomplete integrated art');
    record('All 23 integrated original artwork assets load and decode', {assets:decodedAssets});
    assert(errors.length === 0 && requests.length === 0, 'Runtime or network errors');
    record('No JavaScript exceptions or failed resource requests');
    return {version:'0.6',checkedAt:new Date().toISOString(),status:'PASS',passed:records.length,failed:0,browser:await browser.version(),userAgent:await test.evaluate(()=>navigator.userAgent),viewports:[{width:1280,height:900},{width:390,height:844}],isolation:'Fresh browser context, synthetic fixtures, v0.6 QA namespace. No user saves cleared.',records,errors,requests,limitations:['Agent browser checks, not human playtesting','Real phones, Windows and other browsers NOT_RUN','Team art approval remains a human check']};
  } catch (error) {
    return {status:'FAIL',error:error.stack,records,errors,requests,body:await test.locator('body').innerText()};
  } finally { await context.close(); }
}
